import { createRequire } from 'node:module';
const require = createRequire('/home/user/AgencyOS/package.json');
const { chromium } = require('playwright');
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addCookies([{ name: 'mode', value: 'light', url: 'http://localhost:4200' }]);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message.slice(0, 200)));
await page.goto('http://localhost:4200/agency/dashboard', { waitUntil: 'networkidle', timeout: 180000 });
await page.keyboard.press('Control+j');
await page.waitForTimeout(500);
await page.getByRole('tab', { name: 'Agent' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/agent-empty.png` });
await page.getByLabel('Message the agent').fill('Add a client called Mehta Textiles in the fabric industry');
await page.keyboard.press('Enter');
await page.getByRole('button', { name: 'Approve' }).waitFor({ timeout: 120000 });
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/agent-proposal.png` });
await page.getByRole('button', { name: 'Approve' }).click();
await page.getByText('Approved and done').waitFor({ timeout: 60000 });
await page.waitForFunction(() => document.body.innerText.includes('Mehta'), null, { timeout: 120000 });
await page.waitForTimeout(8000);
await page.screenshot({ path: `${out}/agent-done.png` });
await browser.close();
console.log('ui run complete');
