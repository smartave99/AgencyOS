#!/usr/bin/env node
// Fills installer/RELEASE_NOTES.md with this build's facts, including what the Windows smoke
// test really did, so a release never claims more than was checked.
//
//   node installer/build/release-notes.mjs --version 1.0.0 --sha256 <hash> --commit <sha> --report smoke-report.json --template RELEASE_NOTES.md

import fs from 'node:fs';
import { loadReleases, renderBody } from './changelog.mjs';

const args = process.argv.slice(2);
const opt = (n, d = '') => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : d;
};

const template = fs.readFileSync(opt('--template'), 'utf8');
let report = null;
try {
  report = JSON.parse(fs.readFileSync(opt('--report'), 'utf8'));
} catch {
  /* no evidence available */
}

function verification() {
  if (!report) return '### Verification\n\nNo automated test report was attached to this build.';
  const lines = ['### What was verified for this build', '', 'Before this release was created, the installer was run on a clean Windows machine (GitHub-hosted, Windows Server 2025) and these checks passed:', ''];
  for (const s of report.steps) lines.push(`- ${s.ok ? '✅' : '❌'} ${s.name}`);
  const f = report.facts || {};
  const facts = [];
  if (f.installSeconds) facts.push(`installed in ${f.installSeconds}s`);
  if (f.firstStartSeconds) facts.push(`first start to ready in ${f.firstStartSeconds}s`);
  if (f.restartSeconds) facts.push(`restart to ready in ${f.restartSeconds}s`);
  if (facts.length) lines.push('', `Timings on that machine: ${facts.join(', ')}.`);
  if (f.ai?.hardware) {
    const h = f.ai.hardware;
    lines.push('', `Local AI on that machine (${h.ramGB} GB memory, ${h.threads} threads, ${h.gpu || 'no GPU'}): tier "${f.ai.label}", search model \`${f.ai.models?.embedding?.id}\`, text model \`${f.ai.models?.text?.id || 'none'}\`${f.ai.benchmark ? `, measured ${f.ai.benchmark.tokensPerSecond} tokens/s` : ''}.`);
  }
  if (f.copy?.providerUsed) lines.push(`Ad copy was generated by the \`${f.copy.providerUsed}\` provider in ${f.copy.seconds}s.`);
  if (f.manifest) {
    lines.push('', 'Bundled components:', '');
    for (const [name, t] of Object.entries(f.manifest)) if (name !== 'ollama' && name !== 'vcRuntime') lines.push(`- ${name} ${t.version} (${t.license})`);
    if (f.manifest.ollama) lines.push(`- Ollama ${f.manifest.ollama.version} (downloaded on first start, MIT)`);
  }
  return lines.join('\n');
}

// What changed in this version, from the same file as CHANGELOG.md and the in-app What's new.
function changes() {
  const release = loadReleases().find((r) => r.version === opt('--version'));
  if (!release) throw new Error(`No changelog entry for version ${opt('--version')}: add it to libraries/helpers/src/changelog/releases.json`);
  return [`### What's new in ${release.version}: ${release.title}`, '', renderBody(release), '', 'Every earlier version is listed in `CHANGELOG.md` and under **What\'s new** inside the app.'].join('\n');
}

const out = template
  .replaceAll('{{VERSION}}', opt('--version'))
  .replaceAll('{{SHA256}}', opt('--sha256'))
  .replaceAll('{{COMMIT}}', opt('--commit').slice(0, 12))
  .replace('{{CHANGES}}', changes())
  .replace('{{VERIFICATION}}', verification());
process.stdout.write(out);
